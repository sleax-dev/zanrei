//! Snapshots = one OS restore point + a write-ahead journal of every change Zanrei makes
//! (registry values, scheduled tasks, commands). No change may be made without a snapshot id, and the
//! journal entry is written BEFORE the change, so a crash mid-way is still reversible.

use crate::platform::{Platform, RegKey, RegValue};
use crate::{Error, Result};
use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use std::time::{SystemTime, UNIX_EPOCH};

#[derive(Serialize, Deserialize, Clone, PartialEq, Debug)]
#[serde(tag = "kind")]
pub enum Entry {
    /// `previous: None` = the value did not exist before; rollback deletes it.
    Reg {
        key: RegKey,
        previous: Option<RegValue>,
    },
    Task {
        path: String,
        was_enabled: bool,
    },
    /// A command whose effect is undone by running `revert` (program first, then arguments).
    Cmd {
        revert: Vec<String>,
    },
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Snapshot {
    pub id: String,
    pub created_unix: u64,
    pub label: String,
    pub entries: Vec<Entry>,
    pub rolled_back: bool,
    /// Human-meaningful names of what was changed (tweak ids, "game:option:exe"); shown on the Restore page.
    #[serde(default)]
    pub notes: Vec<String>,
    /// Sequence number of the Windows restore point made with this snapshot, so deleting the snapshot can delete it too.
    #[serde(default)]
    pub restore_point: Option<u32>,
}

#[derive(Clone)]
pub struct Store {
    dir: PathBuf,
}

impl Store {
    pub fn new(dir: PathBuf) -> Self {
        Self {
            dir: dir.join("snapshots"),
        }
    }

    fn path(&self, id: &str) -> PathBuf {
        self.dir.join(format!("{id}.json"))
    }

    fn save(&self, s: &Snapshot) -> Result<()> {
        std::fs::create_dir_all(&self.dir)?;
        let tmp = self.dir.join(format!("{}.tmp", s.id));
        std::fs::write(&tmp, serde_json::to_vec_pretty(s)?)?;
        std::fs::rename(tmp, self.path(&s.id))?;
        Ok(())
    }

    pub fn get(&self, id: &str) -> Result<Snapshot> {
        // ids are generated by us; reject anything that could escape the folder.
        if !id.bytes().all(|b| b.is_ascii_digit()) {
            return Err(Error::Msg("invalid snapshot id".into()));
        }
        Ok(serde_json::from_slice(&std::fs::read(self.path(id))?)?)
    }

    /// Newest first. Unreadable files are skipped rather than hiding every other snapshot.
    pub fn list(&self) -> Vec<Snapshot> {
        let mut all: Vec<Snapshot> = std::fs::read_dir(&self.dir)
            .into_iter()
            .flatten()
            .flatten()
            .filter(|e| e.path().extension().is_some_and(|x| x == "json"))
            .filter_map(|e| serde_json::from_slice(&std::fs::read(e.path()).ok()?).ok())
            .collect();
        all.sort_by(|a, b| b.id.cmp(&a.id));
        all
    }

    /// Creates the OS restore point first; if that fails nothing is created and the caller must not proceed.
    pub fn create(&self, platform: &dyn Platform, label: &str) -> Result<Snapshot> {
        let restore_point = platform.create_restore_point(label)?;
        let now = SystemTime::now().duration_since(UNIX_EPOCH).unwrap_or_default();
        let mut millis = now.as_millis();
        while self.path(&format!("{millis:016}")).exists() {
            millis += 1;
        }
        let snap = Snapshot {
            id: format!("{millis:016}"),
            created_unix: now.as_secs(),
            label: label.into(),
            entries: vec![],
            rolled_back: false,
            notes: vec![],
            restore_point,
        };
        self.save(&snap)?;
        Ok(snap)
    }

    /// Forgets snapshots (what they changed stays as it is; it just can no longer be undone from here) and deletes the
    /// Windows restore points that came with them. Returns `(deleted, windows_points_kept)`: a Windows point that
    /// could not be removed (it may already be gone) does not keep its snapshot alive. Unreadable ids are skipped;
    /// it is an error only when nothing at all could be deleted.
    pub fn delete(&self, platform: &dyn Platform, ids: &[String]) -> Result<(usize, usize)> {
        let mut deleted = vec![];
        let mut first_error = None;
        for id in ids {
            match self.get(id) {
                Ok(snap) => deleted.push((id, snap)),
                Err(e) => {
                    first_error.get_or_insert(e);
                }
            }
        }
        if deleted.is_empty()
            && let Some(e) = first_error
        {
            return Err(e);
        }
        let points: Vec<u32> = deleted.iter().filter_map(|(_, s)| s.restore_point).collect();
        let kept = if points.is_empty() {
            0
        } else {
            // A failed attempt counts every point as kept: the files are still deleted below.
            platform
                .remove_restore_points(&points)
                .map_or(points.len(), |left| left.len())
        };
        let mut count = 0;
        for (id, _) in &deleted {
            if std::fs::remove_file(self.path(id)).is_ok() {
                count += 1;
            }
        }
        Ok((count, kept))
    }

    fn open(&self, id: &str) -> Result<Snapshot> {
        let snap = self.get(id)?;
        if snap.rolled_back {
            return Err(Error::Msg("snapshot already rolled back".into()));
        }
        Ok(snap)
    }

    /// Records what a change was for. Duplicates are ignored; a missing snapshot is an error.
    pub fn note(&self, id: &str, note: &str) -> Result<()> {
        let mut snap = self.open(id)?;
        if !snap.notes.iter().any(|n| n == note) {
            snap.notes.push(note.to_string());
            self.save(&snap)?;
        }
        Ok(())
    }

    /// The only way a registry value is allowed to change.
    pub fn reg_set(&self, platform: &dyn Platform, id: &str, key: &RegKey, value: &RegValue) -> Result<()> {
        self.journal_reg(platform, id, key)?;
        platform.reg_set(key, value)
    }

    pub fn reg_delete(&self, platform: &dyn Platform, id: &str, key: &RegKey) -> Result<()> {
        self.journal_reg(platform, id, key)?;
        platform.reg_delete(key)
    }

    fn journal_reg(&self, platform: &dyn Platform, id: &str, key: &RegKey) -> Result<()> {
        let mut snap = self.open(id)?;
        // First write wins: the original value must survive repeated changes to the same key.
        let known = snap
            .entries
            .iter()
            .any(|e| matches!(e, Entry::Reg { key: k, .. } if k == key));
        if !known {
            snap.entries.push(Entry::Reg {
                key: key.clone(),
                previous: platform.reg_get(key)?,
            });
            self.save(&snap)?;
        }
        Ok(())
    }

    /// Enables or disables a scheduled task. A task that does not exist is left alone.
    pub fn task_set(&self, platform: &dyn Platform, id: &str, path: &str, enabled: bool) -> Result<()> {
        let Some(was_enabled) = platform.task_enabled(path)? else {
            return Ok(());
        };
        let mut snap = self.open(id)?;
        if !snap
            .entries
            .iter()
            .any(|e| matches!(e, Entry::Task { path: p, .. } if p == path))
        {
            snap.entries.push(Entry::Task {
                path: path.into(),
                was_enabled,
            });
            self.save(&snap)?;
        }
        platform.task_set_enabled(path, enabled)
    }

    /// Runs `apply` after journaling the command that undoes it.
    pub fn cmd(&self, platform: &dyn Platform, id: &str, apply: &[&str], revert: &[&str]) -> Result<()> {
        let mut snap = self.open(id)?;
        snap.entries.push(Entry::Cmd {
            revert: revert.iter().map(|s| s.to_string()).collect(),
        });
        self.save(&snap)?;
        let (prog, args) = apply.split_first().ok_or_else(|| Error::Msg("empty command".into()))?;
        platform.run(prog, args).map(|_| ())
    }

    /// Undoes entries newest-first. Keeps going on a failing entry and reports it at the end,
    /// so one bad entry can't block restoring the rest.
    pub fn rollback(&self, platform: &dyn Platform, id: &str) -> Result<()> {
        let mut snap = self.get(id)?;
        let mut failed = vec![];
        for e in snap.entries.iter().rev() {
            let (what, r) = match e {
                Entry::Reg { key, previous } => (
                    format!("{}\\{}", key.path, key.name),
                    match previous {
                        Some(v) => platform.reg_set(key, v),
                        None => platform.reg_delete(key),
                    },
                ),
                Entry::Task { path, was_enabled } => (path.clone(), platform.task_set_enabled(path, *was_enabled)),
                Entry::Cmd { revert } => (
                    revert.join(" "),
                    match revert.split_first() {
                        Some((prog, args)) => {
                            let args: Vec<&str> = args.iter().map(String::as_str).collect();
                            platform.run(prog, &args).map(|_| ())
                        }
                        None => Ok(()),
                    },
                ),
            };
            if let Err(err) = r {
                failed.push(format!("{what}: {err}"));
            }
        }
        if !failed.is_empty() {
            return Err(Error::Msg(format!("could not restore: {}", failed.join("; "))));
        }
        snap.rolled_back = true;
        self.save(&snap)
    }
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use crate::platform::{Gpu, Hive};
    use std::collections::HashMap;
    use std::sync::Mutex;
    use std::sync::atomic::{AtomicU32, Ordering};

    /// In-memory stand-in for the OS, shared by the tests of every module.
    #[derive(Default)]
    pub struct Fake {
        pub reg: Mutex<HashMap<String, RegValue>>,
        pub tasks: Mutex<HashMap<String, bool>>,
        pub ran: Mutex<Vec<String>>,
        pub fail_restore_point: bool,
        pub edge: Mutex<bool>,
        pub apps: Mutex<Vec<String>>,
        pub next_point: AtomicU32,
        pub removed_points: Mutex<Vec<u32>>,
    }

    pub fn k(key: &RegKey) -> String {
        format!("{:?}\\{}\\{}", key.hive, key.path, key.name)
    }

    impl Platform for Fake {
        fn gpus(&self) -> Result<Vec<Gpu>> {
            Ok(vec![])
        }
        fn reg_get(&self, key: &RegKey) -> Result<Option<RegValue>> {
            Ok(self.reg.lock().unwrap().get(&k(key)).cloned())
        }
        fn reg_set(&self, key: &RegKey, v: &RegValue) -> Result<()> {
            self.reg.lock().unwrap().insert(k(key), v.clone());
            Ok(())
        }
        fn reg_delete(&self, key: &RegKey) -> Result<()> {
            self.reg.lock().unwrap().remove(&k(key));
            Ok(())
        }
        fn reg_subkeys(&self, _: Hive, _: &str) -> Result<Vec<String>> {
            Ok(vec![])
        }
        fn reg_value_names(&self, hive: Hive, path: &str) -> Result<Vec<String>> {
            let prefix = format!("{hive:?}\\{path}\\");
            Ok(self
                .reg
                .lock()
                .unwrap()
                .keys()
                .filter_map(|k| k.strip_prefix(&prefix))
                .filter(|rest| !rest.contains('\\'))
                .map(str::to_string)
                .collect())
        }
        fn create_restore_point(&self, _: &str) -> Result<Option<u32>> {
            if self.fail_restore_point {
                Err(Error::Msg("disabled by policy".into()))
            } else {
                Ok(Some(self.next_point.fetch_add(1, Ordering::Relaxed)))
            }
        }
        fn remove_restore_points(&self, sequences: &[u32]) -> Result<Vec<u32>> {
            self.removed_points.lock().unwrap().extend_from_slice(sequences);
            Ok(vec![])
        }
        fn open_system_restore(&self) -> Result<()> {
            Ok(())
        }
        fn run(&self, program: &str, args: &[&str]) -> Result<String> {
            let line = format!("{program} {}", args.join(" "));
            self.ran.lock().unwrap().push(line.clone());
            Ok(match line.as_str() {
                "powercfg /getactivescheme" => {
                    "Power Scheme GUID: 381b4222-f694-41f0-9685-ff5bb260df2e  (Balanced)".into()
                }
                _ => String::new(),
            })
        }
        fn task_enabled(&self, path: &str) -> Result<Option<bool>> {
            Ok(self.tasks.lock().unwrap().get(path).copied())
        }
        fn task_set_enabled(&self, path: &str, enabled: bool) -> Result<()> {
            self.tasks.lock().unwrap().insert(path.into(), enabled);
            Ok(())
        }
        fn edge_installed(&self) -> bool {
            *self.edge.lock().unwrap()
        }
        fn remove_edge(&self) -> Result<()> {
            *self.edge.lock().unwrap() = false;
            Ok(())
        }
        fn installed_apps(&self, names: &[&str]) -> Result<Vec<String>> {
            Ok(self
                .apps
                .lock()
                .unwrap()
                .iter()
                .filter(|a| names.contains(&a.as_str()))
                .cloned()
                .collect())
        }
        fn remove_apps(&self, names: &[&str]) -> Result<()> {
            self.apps.lock().unwrap().retain(|a| !names.contains(&a.as_str()));
            Ok(())
        }
        fn recycle_bin_size(&self) -> Result<u64> {
            Ok(0)
        }
        fn empty_recycle_bin(&self) -> Result<()> {
            Ok(())
        }
    }

    pub fn key(name: &str) -> RegKey {
        RegKey::new(Hive::Hkcu, "Software\\Zanrei", name)
    }

    #[test]
    fn rollback_restores_original_values_and_removes_new_ones() {
        let dir = tempfile::tempdir().unwrap();
        let (store, p) = (Store::new(dir.path().into()), Fake::default());
        p.reg_set(&key("A"), &RegValue::Dword(1)).unwrap();

        let s = store.create(&p, "test").unwrap();
        store.reg_set(&p, &s.id, &key("A"), &RegValue::Dword(2)).unwrap();
        store.reg_set(&p, &s.id, &key("A"), &RegValue::Dword(3)).unwrap(); // second write must not overwrite the original
        store
            .reg_set(&p, &s.id, &key("B"), &RegValue::String("x".into()))
            .unwrap();
        assert_eq!(p.reg_get(&key("A")).unwrap(), Some(RegValue::Dword(3)));

        store.rollback(&p, &s.id).unwrap();
        assert_eq!(p.reg_get(&key("A")).unwrap(), Some(RegValue::Dword(1)));
        assert_eq!(p.reg_get(&key("B")).unwrap(), None);
        assert!(store.get(&s.id).unwrap().rolled_back);
        assert!(store.reg_set(&p, &s.id, &key("A"), &RegValue::Dword(9)).is_err());
    }

    #[test]
    fn rollback_restores_deleted_values_tasks_and_commands() {
        let dir = tempfile::tempdir().unwrap();
        let (store, p) = (Store::new(dir.path().into()), Fake::default());
        p.reg_set(&key("A"), &RegValue::Binary(vec![1, 2])).unwrap();
        p.tasks.lock().unwrap().insert("\\T".into(), true);

        let s = store.create(&p, "test").unwrap();
        store.reg_delete(&p, &s.id, &key("A")).unwrap();
        store.task_set(&p, &s.id, "\\T", false).unwrap();
        store.task_set(&p, &s.id, "\\Missing", false).unwrap(); // absent task: silently skipped
        store
            .cmd(&p, &s.id, &["powercfg", "/h", "off"], &["powercfg", "/h", "on"])
            .unwrap();
        assert_eq!(p.reg_get(&key("A")).unwrap(), None);
        assert_eq!(p.task_enabled("\\T").unwrap(), Some(false));
        assert_eq!(store.get(&s.id).unwrap().entries.len(), 3);

        store.rollback(&p, &s.id).unwrap();
        assert_eq!(p.reg_get(&key("A")).unwrap(), Some(RegValue::Binary(vec![1, 2])));
        assert_eq!(p.task_enabled("\\T").unwrap(), Some(true));
        assert_eq!(p.ran.lock().unwrap().last().unwrap(), "powercfg /h on");
    }

    #[test]
    fn notes_are_kept_once_and_old_snapshots_still_load() {
        let dir = tempfile::tempdir().unwrap();
        let (store, p) = (Store::new(dir.path().into()), Fake::default());
        let s = store.create(&p, "test").unwrap();
        store.note(&s.id, "telemetry").unwrap();
        store.note(&s.id, "telemetry").unwrap();
        assert_eq!(store.get(&s.id).unwrap().notes, ["telemetry"]);
        // a snapshot file written before notes existed has no such field
        let old = r#"{"id":"1","created_unix":1,"label":"x","entries":[],"rolled_back":false}"#;
        std::fs::write(dir.path().join("snapshots/0000000000000001.json"), old).unwrap();
        assert!(store.get("0000000000000001").unwrap().notes.is_empty());
    }

    #[test]
    fn no_snapshot_when_restore_point_fails() {
        let dir = tempfile::tempdir().unwrap();
        let (store, p) = (
            Store::new(dir.path().into()),
            Fake {
                fail_restore_point: true,
                ..Default::default()
            },
        );
        assert!(store.create(&p, "test").is_err());
        assert!(store.list().is_empty());
    }

    #[test]
    fn deleting_snapshots_removes_their_windows_restore_points_too() {
        let dir = tempfile::tempdir().unwrap();
        let (store, p) = (Store::new(dir.path().into()), Fake::default());
        let (a, b) = (store.create(&p, "a").unwrap(), store.create(&p, "b").unwrap());
        assert_eq!(store.list().len(), 2);
        assert_eq!(store.delete(&p, std::slice::from_ref(&a.id)).unwrap(), (1, 0));
        assert_eq!(store.list().len(), 1);
        assert_eq!(*p.removed_points.lock().unwrap(), vec![a.restore_point.unwrap()]);
        assert!(store.get(&b.id).is_ok());
        // a gone id is an error on its own, but not when other snapshots were deleted with it
        assert!(store.delete(&p, std::slice::from_ref(&a.id)).is_err());
        // a snapshot from before restore points were numbered has nothing to remove
        let old = r#"{"id":"1","created_unix":1,"label":"x","entries":[],"rolled_back":false}"#;
        std::fs::write(dir.path().join("snapshots/0000000000000001.json"), old).unwrap();
        assert_eq!(
            store
                .delete(&p, &["0000000000000001".into(), b.id.clone(), a.id.clone()])
                .unwrap(),
            (2, 0)
        );
        assert!(store.list().is_empty());
    }

    #[test]
    fn rejects_path_traversal_ids() {
        let dir = tempfile::tempdir().unwrap();
        assert!(Store::new(dir.path().into()).get("..\\..\\x").is_err());
    }
}
